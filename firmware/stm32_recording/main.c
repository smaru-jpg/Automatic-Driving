void drive_pwm(int left_pwm, int right_pwm)
{
    // RIGHT Motor (TIM1)
    if (right_pwm >= 0)
    {
        HAL_GPIO_WritePin(GPIOA, GPIO_PIN_4, GPIO_PIN_RESET);
        HAL_GPIO_WritePin(GPIOA, GPIO_PIN_5, GPIO_PIN_SET);
    }
    else
    {
        HAL_GPIO_WritePin(GPIOA, GPIO_PIN_4, GPIO_PIN_SET);
        HAL_GPIO_WritePin(GPIOA, GPIO_PIN_5, GPIO_PIN_RESET);
        right_pwm = -right_pwm;
    }
    if (right_pwm > 4199) right_pwm = 4199;
    __HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_1, right_pwm);
    __HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_2, right_pwm);

    // LEFT Motor (TIM3)
    if (left_pwm >= 0)
    {
        HAL_GPIO_WritePin(GPIOB, GPIO_PIN_0, GPIO_PIN_SET);
        HAL_GPIO_WritePin(GPIOB, GPIO_PIN_1, GPIO_PIN_RESET);
    }
    else
    {
        HAL_GPIO_WritePin(GPIOB, GPIO_PIN_0, GPIO_PIN_RESET);
        HAL_GPIO_WritePin(GPIOB, GPIO_PIN_1, GPIO_PIN_SET);
        left_pwm = -left_pwm;
    }
    if (left_pwm > 4199) left_pwm = 4199;
    __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_1, left_pwm);
    __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_2, left_pwm);
}

void replay_motion(void)
{
    isReplaying = 1;

    for(int i = 0; i < log_index; i++)
    {
        drive_pwm(left_pwm_log[i], right_pwm_log[i]);
        HAL_Delay(10);   // 기록했던 주기와 동일하게 실행
    }

    drive_pwm(0, 0);
    isReplaying = 0;
}

